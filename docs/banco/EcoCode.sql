CREATE TABLE IF NOT EXISTS usuarios (
  id VARCHAR(36) PRIMARY KEY,
  nome_completo VARCHAR(255) NOT NULL,
  cpf VARCHAR(14) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  senha_criptografada TEXT NOT NULL,
  cargo VARCHAR(32) NOT NULL CHECK (cargo IN ('GERENTE', 'FUNCIONARIO', 'USUARIO')),
  data_nascimento DATE NOT NULL,
  bairro VARCHAR(64) NOT NULL CHECK (bairro IN ('SETOR_CENTRAL', 'SETOR_OESTE', 'SETOR_CAMPINAS', 'SETOR_LESTE_UNIVERSITARIO', 'SETOR_BUENO', 'SETOR_MARISTA', 'JARDIM_GOIAS', 'SETOR_PEDRO_LUDOVICO', 'JARDIM_AMERICA', 'PARQUE_AMAZONIA', 'SETOR_JAO', 'JARDIM_GUANABARA', 'JARDIM_NOVO_MUNDO', 'CIDADE_JARDIM', 'JARDIM_CURITIBA', 'SETOR_FAICALVILLE', 'RESIDENCIAL_CAMPOS_DOURADOS', 'JARDIM_SAO_JOSE', 'PARQUE_ELDORADO_OESTE'))
);
CREATE TABLE IF NOT EXISTS residuos (
  id VARCHAR(36) PRIMARY KEY,
  id_usuario VARCHAR(36) NOT NULL,
  codigo VARCHAR(6) NOT NULL UNIQUE,
  tipo_residuo VARCHAR(32) NOT NULL CHECK (tipo_residuo IN ('COMPUTADORES', 'CELULARES', 'CABOS', 'BATERIAS', 'OUTROS')),
  quantidade INT NOT NULL,
  descricao TEXT,
  status VARCHAR(32) NOT NULL CHECK (status IN ('DISPONIVEL', 'EM_SOLICITACAO', 'DESCARTADO')),
  FOREIGN KEY (id_usuario) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS solicitacoes (
  id VARCHAR(36) PRIMARY KEY,
  id_usuario VARCHAR(36) NOT NULL,
  id_residuo VARCHAR(36) NOT NULL,
  status VARCHAR(32) NOT NULL CHECK (status IN ('PENDENTE', 'EM_ROTA', 'CONCLUIDA', 'CANCELADA')),
  data_solicitacao DATETIME(6) NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuarios(id),
  FOREIGN KEY (id_residuo) REFERENCES residuos(id)
);
CREATE TABLE IF NOT EXISTS ponto_coleta (
  id VARCHAR(36) PRIMARY KEY,
  nome VARCHAR(255) NOT NULL,
  endereco VARCHAR(255) NOT NULL,
  bairro VARCHAR(64) NOT NULL CHECK (bairro IN ('SETOR_CENTRAL', 'SETOR_OESTE', 'SETOR_CAMPINAS', 'SETOR_LESTE_UNIVERSITARIO', 'SETOR_BUENO', 'SETOR_MARISTA', 'JARDIM_GOIAS', 'SETOR_PEDRO_LUDOVICO', 'JARDIM_AMERICA', 'PARQUE_AMAZONIA', 'SETOR_JAO', 'JARDIM_GUANABARA', 'JARDIM_NOVO_MUNDO', 'CIDADE_JARDIM', 'JARDIM_CURITIBA', 'SETOR_FAICALVILLE', 'RESIDENCIAL_CAMPOS_DOURADOS', 'JARDIM_SAO_JOSE', 'PARQUE_ELDORADO_OESTE'))
);
CREATE TABLE IF NOT EXISTS logs_auditoria (
  id VARCHAR(36) PRIMARY KEY,
  id_usuario VARCHAR(36) NOT NULL,
  acao_log VARCHAR(32) NOT NULL CHECK (acao_log IN ('CADASTROU_USUARIO', 'EDITOU_USUARIO', 'PROMOVEU_USUARIO', 'REMOVEU_USUARIO', 'CADASTROU_PONTO', 'EDITOU_PONTO', 'EXCLUIU_PONTO', 'PEGOU_SOLICITACAO', 'CONCLUIU_SOLICITACAO', 'CANCELOU_SOLICITACAO')),
  alvo TEXT,
  data_registro DATETIME(6) NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS sessoes (
  token VARCHAR(255) PRIMARY KEY,
  id_usuario VARCHAR(36) NOT NULL,
  expiracao DATETIME NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuarios(id)
);
